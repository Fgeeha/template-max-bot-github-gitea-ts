/** Строки таблиц БД в camelCase. SQL и маппинг колонок — в src/db/repositories/. */

/**
 * Раздел меню — узел дерева.
 *
 * Корень (parentId === null) один: его text — приветствие на /start, а
 * дочерние разделы — кнопки главного меню. У любого раздела text
 * отправляется при нажатии на его кнопку; если есть подразделы, под текстом
 * появляются их кнопки. Раздел со ссылкой (url) — кнопка-ссылка наружу.
 */
export interface Section {
  id: number;
  parentId: number | null;
  /** Подпись кнопки, до 64 символов — потолок MAX. */
  title: string;
  text: string;
  /** Порядок кнопок среди соседей. */
  position: number;
  /** Задана — кнопка открывает ссылку, текст и подразделы пользователь не видит. */
  url: string | null;
  /**
   * Токен картинки MAX — присылается над текстом раздела. Это токен входящего
   * фото из админки: MAX разрешает отправить то же вложение повторно, файл
   * бот не хранит.
   */
  imageToken: string | null;
}

/**
 * Администратор, добавленный владельцем через админку. Владельцы — ADMIN_IDS
 * из .env — сюда не пишутся: их права не зависят от БД.
 */
export interface Staff {
  userId: number;
  addedBy: number | null;
  createdAt: Date;
}

/**
 * Запись журнала изменений. details — готовая строка для показа: раздел мог
 * быть удалён, поэтому название сохраняется на момент правки.
 */
export interface AuditEntry {
  id: number;
  userId: number;
  details: string;
  createdAt: Date;
}
